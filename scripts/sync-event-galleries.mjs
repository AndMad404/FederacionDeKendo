import { createHash } from "node:crypto";
import {
  cp,
  mkdir,
  readFile,
  rename,
  rm,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DRIVE_FOLDER = /^https:\/\/drive\.google\.com\/drive\/folders\/([A-Za-z0-9_-]+)(?:[/?#].*)?$/;
const INPUT_FORMATS = new Set(["jpeg", "png", "webp", "avif"]);
const MAX_BYTES = 20 * 1024 * 1024;
const MIN_WIDTH = 480;
const MIN_HEIGHT = 320;
const MAX_LONG_EDGE = 3840;
const MAX_PIXELS = 3840 * 2160;
const WIDTHS = [480, 960, 1600];
const SIZES = "(max-width: 640px) 100vw, 960px";
const collator = new Intl.Collator("en", { numeric: true, sensitivity: "base" });

export const EVENT_GALLERY_LIMITS = Object.freeze({
  maxBytes: MAX_BYTES,
  minWidth: MIN_WIDTH,
  minHeight: MIN_HEIGHT,
  maxLongEdge: MAX_LONG_EDGE,
  maxPixels: MAX_PIXELS,
  inputFormats: [...INPUT_FORMATS],
  outputFormats: ["webp", "avif"],
});

export function getDriveFolderId(albumUrl) {
  return DRIVE_FOLDER.exec(albumUrl ?? "")?.[1];
}

function digest(value) {
  return createHash("sha256").update(value).digest("hex");
}

async function readJson(filePath, fallback) {
  try {
    return JSON.parse(await readFile(filePath, "utf8"));
  } catch (error) {
    if (error?.code === "ENOENT") return fallback;
    throw error;
  }
}

export function extractDriveFiles(html) {
  const match = /window\['_DRIVE_ivd'\]\s*=\s*'((?:\\.|[^'])+)'/.exec(html);
  if (!match) throw new Error("Google Drive folder is not publicly readable.");
  const serialized = match[1]
    .replace(/\\x([\dA-Fa-f]{2})/g, "\\u00$1")
    .replace(/"/g, '\\"');
  const decoded = JSON.parse(`"${serialized}"`);
  const rows = JSON.parse(decoded);
  const files = [];
  const visit = (value) => {
    if (!Array.isArray(value)) return;
    if (
      typeof value[0] === "string" &&
      typeof value[2] === "string" &&
      value[3]?.startsWith?.("image/")
    ) {
      files.push({ id: value[0], name: value[2] });
      return;
    }
    for (const child of value) visit(child);
  };
  visit(rows);
  return files;
}

async function listPublicDriveFolder(albumUrl, fetchImpl = fetch) {
  const folderId = getDriveFolderId(albumUrl);
  if (!folderId) throw new Error("Only Google Drive public folder URLs are accepted.");
  const response = await fetchImpl(`https://drive.google.com/drive/folders/${folderId}`);
  if (!response.ok) throw new Error("Google Drive folder is not publicly readable.");
  return extractDriveFiles(await response.text());
}

async function downloadDriveFile(file, fetchImpl = fetch) {
  const response = await fetchImpl(
    `https://drive.usercontent.google.com/download?id=${encodeURIComponent(file.id)}&export=download&confirm=t`,
  );
  if (!response.ok) throw new Error(`Download failed for ${file.name}.`);
  return Buffer.from(await response.arrayBuffer());
}

async function inspectImage(buffer, name) {
  if (buffer.length > MAX_BYTES) throw new Error(`${name}: file exceeds 20 MB.`);
  let metadata;
  try {
    metadata = await sharp(buffer, { failOn: "error", limitInputPixels: MAX_PIXELS }).metadata();
  } catch {
    throw new Error(`${name}: invalid image content or dimensions.`);
  }
  if (!INPUT_FORMATS.has(metadata.format)) throw new Error(`${name}: unsupported real MIME.`);
  const rotated = [5, 6, 7, 8].includes(metadata.orientation);
  const width = rotated ? metadata.height : metadata.width;
  const height = rotated ? metadata.width : metadata.height;
  if (
    !width ||
    !height ||
    Math.max(width, height) < MIN_WIDTH ||
    Math.min(width, height) < MIN_HEIGHT
  ) {
    throw new Error(`${name}: image is smaller than 480 x 320.`);
  }
  if (Math.max(width, height) > MAX_LONG_EDGE || width * height > MAX_PIXELS) {
    throw new Error(`${name}: image exceeds orientation-independent 4K.`);
  }
  const pixels = await sharp(buffer).rotate().removeAlpha().raw().toBuffer();
  return { width, height, pixelHash: digest(pixels) };
}

async function createVariants(buffer, eventDirectory, baseName, width) {
  const formats = [];
  for (const format of ["webp", "avif"]) {
    const fileName = `${baseName}-${width}.${format}`;
    const outputPath = path.join(eventDirectory, fileName);
    let pipeline = sharp(buffer).rotate().resize({ width, withoutEnlargement: true });
    pipeline = format === "webp"
      ? pipeline.webp({ quality: 72, effort: 6 })
      : pipeline.avif({ quality: 45, effort: 7 });
    const info = await pipeline.toFile(outputPath);
    formats.push({ format, fileName, width: info.width, height: info.height });
  }
  return formats;
}

function serializeManifest(galleries) {
  return `// Auto-generated by the event gallery pipeline. Do not edit manually.\n` +
    `interface EventGalleryImage {\n  order: number;\n  alt: string;\n  width: number;\n  height: number;\n  src: string;\n  srcSet: { webp: string; avif: string };\n  sizes: string;\n}\n\n` +
    `export interface EventGallery { fingerprint: string; images: EventGalleryImage[] }\n\n` +
    `export const EVENT_GALLERIES: Record<string, EventGallery> = ${JSON.stringify(galleries, null, 2)};\n`;
}

export async function replaceTransaction(entries) {
  const backups = [];
  const published = [];
  try {
    for (const { target, staged } of entries) {
      const backup = `${target}.${process.pid}.backup`;
      try {
        await rename(target, backup);
        backups.push({ target, backup });
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }
      await rename(staged, target);
      published.push(target);
    }
    await Promise.all(backups.map(({ backup }) => rm(backup, { recursive: true, force: true })));
  } catch (error) {
    await Promise.all(entries.map(({ staged }) => rm(staged, { recursive: true, force: true })));
    await Promise.all(published.map((target) => rm(target, { recursive: true, force: true })));
    await Promise.all(backups.map(({ target, backup }) => rename(backup, target)));
    throw error;
  }
}

export async function synchronizeEventGalleries({
  events,
  manifestPath = path.join(ROOT, "src/app/data/eventGalleries.ts"),
  statePath = path.join(ROOT, "src/app/data/eventGalleryState.json"),
  imagesRoot = path.join(ROOT, "public/images/events"),
  listFolder = listPublicDriveFolder,
  downloadFile = downloadDriveFile,
  deferPublish = false,
} = {}) {
  const warnings = [];
  const alarms = [];
  const previousState = await readJson(statePath, { version: 1, galleries: {} });
  let previousGalleries = {};
  try {
    const source = await readFile(manifestPath, "utf8");
    const json = /EVENT_GALLERIES[^=]*=\s*(\{[\s\S]*\});\s*$/.exec(source)?.[1];
    if (json) previousGalleries = JSON.parse(json);
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  const nextState = structuredClone(previousState);
  const nextGalleries = structuredClone(previousGalleries);
  let hasNewGallery = false;
  let importedCount = 0;
  const stage = `${imagesRoot}.${process.pid}.stage`;
  await rm(stage, { recursive: true, force: true });
  await mkdir(path.dirname(stage), { recursive: true });
  try {
    await cp(imagesRoot, stage, { recursive: true });
  } catch (error) {
    if (error?.code === "ENOENT") await mkdir(stage, { recursive: true });
    else throw error;
  }

  for (const event of events ?? []) {
    const stateFrozen = previousState.galleries?.[event.slug];
    const manifestFrozen = previousGalleries[event.slug];
    if (stateFrozen && manifestFrozen && stateFrozen.fingerprint !== manifestFrozen.fingerprint) {
      warnings.push(`${event.slug}: gallery state is inconsistent; published gallery preserved.`);
      alarms.push({
        slug: event.slug,
        status: "galeria_congelada_cambio_detectado",
        reason: "estado_incompatible",
      });
      continue;
    }
    const frozen = stateFrozen ?? manifestFrozen;
    if (frozen) continue;
    if (!event.albumUrl) {
      alarms.push({
        slug: event.slug,
        status: frozen ? "galeria_congelada_cambio_detectado" : "album_aun_no_publicado",
        reason: frozen ? "album_retirado" : "album_ausente",
      });
      continue;
    }
    if (!getDriveFolderId(event.albumUrl)) {
      warnings.push(`${event.slug}: invalid Google Drive folder URL.`);
      alarms.push({
        slug: event.slug,
        status: frozen ? "galeria_congelada_cambio_detectado" : "album_aun_no_publicado",
        reason: "album_invalido",
      });
      continue;
    }
    try {
      const files = (await listFolder(event.albumUrl)).sort((a, b) => collator.compare(a.name, b.name));
      const valid = [];
      let invalidFile = false;
      const seen = new Set();
      for (const file of files) {
        try {
          const buffer = await downloadFile(file);
          const inspected = await inspectImage(buffer, file.name);
          if (seen.has(inspected.pixelHash)) {
            warnings.push(`${event.slug}: duplicate ignored.`);
            continue;
          }
          seen.add(inspected.pixelHash);
          valid.push({ file, buffer, ...inspected });
        } catch (error) {
          invalidFile = true;
          warnings.push(`${event.slug}: ${error.message}`);
        }
      }
      if (valid.length === 0 || (invalidFile && valid.length < 5)) {
        warnings.push(`${event.slug}: partial or invalid import; previous gallery preserved.`);
        alarms.push({
          slug: event.slug,
          status: frozen ? "galeria_congelada_cambio_detectado" : "album_aun_no_publicado",
          reason: "importacion_invalida",
        });
        continue;
      }
      if (valid.length > 5) warnings.push(`${event.slug}: additional files ignored.`);
      const selected = valid.slice(0, 5);
      const fingerprint = digest(selected.map((item) => `${item.file.name}:${item.pixelHash}`).join("\n"));
      if (frozen) {
        if (!stateFrozen) {
          nextState.galleries[event.slug] = { fingerprint: frozen.fingerprint };
          hasNewGallery = true;
        }
        if (frozen.fingerprint !== fingerprint) {
          warnings.push(`${event.slug}: Drive changed; frozen gallery preserved.`);
          alarms.push({
            slug: event.slug,
            status: "galeria_congelada_cambio_detectado",
            reason: "album_modificado",
          });
        }
        continue;
      }
      const eventDirectory = path.join(stage, event.slug);
      await rm(eventDirectory, { recursive: true, force: true });
      await mkdir(eventDirectory, { recursive: true });
      const images = [];
      for (const [index, item] of selected.entries()) {
        const baseName = `photo-${index + 1}`;
        const widths = WIDTHS.filter((width) => width <= item.width);
        if (!widths.includes(item.width) && item.width < WIDTHS.at(-1)) widths.push(item.width);
        const variants = [];
        for (const width of widths) variants.push(...await createVariants(item.buffer, eventDirectory, baseName, width));
        const byFormat = Object.groupBy(variants, (variant) => variant.format);
        const largest = variants.toSorted((a, b) => b.width - a.width)[0];
        const publicBase = `/images/events/${event.slug}/`;
        images.push({
          order: index + 1,
          alt: `Federaciones de Asociaciones de Kendo - ${event.title} ${event.date}`,
          width: largest.width,
          height: largest.height,
          src: `${publicBase}${baseName}-${largest.width}.webp`,
          srcSet: Object.fromEntries(Object.entries(byFormat).map(([format, values]) => [
            format,
            values.map((value) => `${publicBase}${value.fileName} ${value.width}w`).join(", "),
          ])),
          sizes: SIZES,
        });
      }
      nextGalleries[event.slug] = { fingerprint, images };
      nextState.galleries[event.slug] = { fingerprint };
      hasNewGallery = true;
      importedCount += 1;
    } catch (error) {
      warnings.push(`${event.slug}: gallery access or download failed; previous gallery preserved.`);
      alarms.push({
        slug: event.slug,
        status: frozen ? "galeria_congelada_cambio_detectado" : "album_aun_no_publicado",
        reason: "acceso_o_descarga_fallida",
      });
    }
  }

  if (!hasNewGallery) {
    await rm(stage, { recursive: true, force: true });
    return { galleries: nextGalleries, state: nextState, warnings, alarms, importedCount };
  }

  const manifestStage = `${manifestPath}.${process.pid}.stage`;
  const stateStage = `${statePath}.${process.pid}.stage`;
  await mkdir(path.dirname(manifestStage), { recursive: true });
  await writeFile(manifestStage, serializeManifest(nextGalleries));
  await writeFile(stateStage, `${JSON.stringify(nextState, null, 2)}\n`);
  const publication = [
    { target: imagesRoot, staged: stage },
    { target: manifestPath, staged: manifestStage },
    { target: statePath, staged: stateStage },
  ];
  if (!deferPublish) await replaceTransaction(publication);
  return { galleries: nextGalleries, state: nextState, warnings, alarms, publication, importedCount };
}
